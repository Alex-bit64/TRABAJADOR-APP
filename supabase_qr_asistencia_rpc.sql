CREATE OR REPLACE FUNCTION public.registrar_tracking_personal(
    p_dni TEXT,
    p_token TEXT DEFAULT NULL,
    p_id_tienda_qr TEXT DEFAULT NULL,
    p_nombre_tienda TEXT DEFAULT NULL,
    p_direccion_tienda TEXT DEFAULT NULL,
    p_latitud DOUBLE PRECISION DEFAULT NULL,
    p_longitud DOUBLE PRECISION DEFAULT NULL,
    p_nombre_trabajador TEXT DEFAULT NULL,
    p_cargo_trabajador TEXT DEFAULT NULL,
    p_id_trabajador TEXT DEFAULT NULL,
    p_id_tienda_asignada TEXT DEFAULT NULL,
    p_tipo_marcacion TEXT DEFAULT 'Marca',
    p_origen TEXT DEFAULT 'multiple',
    p_tipo TEXT DEFAULT NULL,
    p_registrado_en TEXT DEFAULT NULL
)
RETURNS TABLE (
    ok BOOLEAN,
    mensaje TEXT,
    fecha TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_token TEXT := public.normalizar_token_qr(COALESCE(p_token, ''));
    v_registrado_en TIMESTAMPTZ;
    v_id_tienda_qr TEXT;
    v_tipo TEXT;
    v_ubicacion JSONB;
    v_ubicacion_qr JSONB := '{}'::JSONB;
    v_referencia_qr JSONB;
    v_distancia_qr DOUBLE PRECISION;
BEGIN
    IF p_dni IS NULL OR trim(p_dni) = '' THEN
        RETURN QUERY SELECT FALSE, 'Falta el DNI del trabajador para registrar tracking.', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    BEGIN
        v_registrado_en := COALESCE(NULLIF(trim(COALESCE(p_registrado_en, '')), '')::TIMESTAMPTZ, date_trunc('second', now()));
    EXCEPTION WHEN OTHERS THEN
        v_registrado_en := date_trunc('second', now());
    END;

    SELECT
        q.id_tienda::TEXT,
        COALESCE(q.ubicacion, '{}'::JSONB)
    INTO
        v_id_tienda_qr,
        v_ubicacion_qr
    FROM public.qr q
    INNER JOIN public.tienda t ON t.id_tienda = q.id_tienda
    WHERE t.estado = TRUE
      AND (
          trim(q.token::TEXT) = v_token
          OR public.payload_qr_valido_tienda(v_token, q.id_tienda)
      )
    LIMIT 1;

    v_id_tienda_qr := COALESCE(NULLIF(trim(COALESCE(p_id_tienda_qr, '')), ''), v_id_tienda_qr, '');
    v_tipo := CASE
        WHEN upper(trim(COALESCE(p_tipo, ''))) = 'NORMAL'
          OR lower(trim(COALESCE(p_origen, ''))) = 'normal'
        THEN 'NORMAL'
        ELSE 'MULTIPLE'
    END;
    v_ubicacion := jsonb_strip_nulls(jsonb_build_object(
        'latitud', p_latitud,
        'longitud', p_longitud
    ));

    IF v_tipo = 'MULTIPLE' AND NOT EXISTS (
        SELECT 1
        FROM public.asistencia a
        WHERE a.dni_trabajador::TEXT = trim(p_dni)
          AND a.fecha = (v_registrado_en AT TIME ZONE 'America/Lima')::DATE
          AND a.horario_entrada IS NOT NULL
          AND a.horario_entrada <= v_registrado_en
    ) THEN
        RETURN QUERY SELECT FALSE, 'Primero registra tu Entrada antes de usar Tracking.', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    v_referencia_qr := public.extraer_ubicacion_qr(v_ubicacion_qr, p_tipo_marcacion);
    IF v_referencia_qr IS NULL THEN
        RETURN QUERY SELECT FALSE, 'El QR no tiene ubicacion de referencia para validar el rango.', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF NULLIF(v_referencia_qr ->> 'latitud', '') IS NULL
       OR NULLIF(v_referencia_qr ->> 'longitud', '') IS NULL THEN
        RETURN QUERY SELECT FALSE, 'El QR no tiene ubicacion de referencia para validar el rango.', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF p_latitud IS NULL
       OR p_longitud IS NULL
       OR (
           abs(COALESCE(p_latitud, 0)) <= 0.000001
           AND abs(COALESCE(p_longitud, 0)) <= 0.000001
       ) THEN
        RETURN QUERY SELECT FALSE, 'No se pudo obtener tu ubicacion actual para validar el QR.', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    v_distancia_qr := public.distancia_metros(
        NULLIF(v_referencia_qr ->> 'latitud', '')::DOUBLE PRECISION,
        NULLIF(v_referencia_qr ->> 'longitud', '')::DOUBLE PRECISION,
        p_latitud,
        p_longitud
    );

    IF v_distancia_qr > 150 THEN
        RETURN QUERY SELECT FALSE, 'Fuera del rango permitido del QR. Acercate a la sede para marcar.', NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.asistencia_multiple a
        WHERE a.id_trabajador::TEXT = trim(p_dni)
          AND a.hora_marca = v_registrado_en
          AND COALESCE(a.id_tienda, '') = COALESCE(v_id_tienda_qr, '')
          AND COALESCE(a.tipo, '') = v_tipo
        LIMIT 1
    ) THEN
        UPDATE public.asistencia_multiple a
        SET ubicacion = v_ubicacion
        WHERE a.id_trabajador::TEXT = trim(p_dni)
          AND a.hora_marca = v_registrado_en
          AND COALESCE(a.id_tienda, '') = COALESCE(v_id_tienda_qr, '')
          AND COALESCE(a.tipo, '') = v_tipo
          AND v_ubicacion <> '{}'::JSONB
          AND (
              a.ubicacion IS NULL
              OR a.ubicacion = '{}'::JSONB
              OR (
                  COALESCE(NULLIF(a.ubicacion ->> 'latitud', '')::DOUBLE PRECISION, 0) = 0
                  AND COALESCE(NULLIF(a.ubicacion ->> 'longitud', '')::DOUBLE PRECISION, 0) = 0
              )
          );
        RETURN QUERY SELECT TRUE, 'Movimiento ya registrado', v_registrado_en;
        RETURN;
    END IF;

    INSERT INTO public.asistencia_multiple (
        id_trabajador,
        id_tienda,
        hora_marca,
        ubicacion,
        tipo
    )
    VALUES (
        trim(p_dni),
        v_id_tienda_qr,
        v_registrado_en,
        v_ubicacion,
        v_tipo
    );

    RETURN QUERY SELECT TRUE, 'Movimiento registrado', v_registrado_en;
END;
$$;

