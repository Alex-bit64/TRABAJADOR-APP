    v_ultima_tienda_tracking TEXT;
    v_ultimo_tipo_tracking TEXT;
    v_tipo_jornada_manual TEXT;
BEGIN
    IF p_marcado_en IS NOT NULL AND p_evento_id IS NULL THEN
        RETURN QUERY SELECT FALSE, 'La fecha original requiere un identificador de evento offline.', NULL::TEXT,
            NULL::UUID, v_fecha AS fecha_asistencia, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF p_marcado_en IS NOT NULL
       AND (p_marcado_en > now() + INTERVAL '5 minutes'
            OR p_marcado_en < now() - INTERVAL '30 days') THEN
        RETURN QUERY SELECT FALSE, 'La fecha de la marcacion offline esta fuera del rango permitido.', NULL::TEXT,
            NULL::UUID, v_fecha AS fecha_asistencia, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF p_dni IS NULL OR trim(p_dni) = '' THEN
        RETURN QUERY SELECT FALSE, 'Falta el DNI del trabajador para registrar asistencia.', NULL::TEXT,
            NULL::UUID, v_fecha AS fecha_asistencia, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    SELECT t.estado, COALESCE(t.biometria_requerida, FALSE)
    INTO v_trabajador_activo, v_biometria_requerida
    FROM public.trabajador t
    WHERE t.dni = trim(p_dni)
    LIMIT 1;

    IF v_trabajador_activo IS DISTINCT FROM TRUE THEN
        RETURN QUERY SELECT FALSE, 'Trabajador no encontrado o inactivo.', NULL::TEXT,
            NULL::UUID, v_fecha AS fecha_asistencia, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF v_biometria_requerida
       AND NOT public.dispositivo_trabajador_valido(
           trim(p_dni),
           p_dispositivo_id,
           p_dispositivo_secreto
       ) THEN
        RETURN QUERY SELECT FALSE,
            'Este dispositivo no esta autorizado para registrar la asistencia del trabajador.',
            NULL::TEXT,
            NULL::UUID,
            v_fecha AS fecha_asistencia,
            NULL::TIMESTAMPTZ,
            NULL::TIMESTAMPTZ,
            NULL::TIMESTAMPTZ,
            NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    IF p_evento_id IS NOT NULL THEN
        PERFORM pg_advisory_xact_lock(hashtext(p_evento_id::TEXT));
        SELECT e.tipo_marcacion
        INTO v_tipo
        FROM public.marcacion_offline_evento e
        WHERE e.evento_id = p_evento_id
          AND e.dni_trabajador = trim(p_dni)
        LIMIT 1;

        IF v_tipo IS NOT NULL THEN
            SELECT a.*
            INTO v_asistencia
            FROM public.marcacion_offline_evento e
            JOIN public.asistencia a ON a.id_asistencia = e.id_asistencia
            WHERE e.evento_id = p_evento_id
              AND e.dni_trabajador = trim(p_dni)
            LIMIT 1;

            IF v_asistencia.id_asistencia IS NOT NULL THEN
                RETURN QUERY SELECT TRUE,
                    CASE v_tipo
                        WHEN 'horario_entrada' THEN 'Entrada'
                        WHEN 'horario_inicio_receso' THEN 'Inicio de receso'
                        WHEN 'horario_fin_receso' THEN 'Fin de receso'
                        WHEN 'horario_salida' THEN 'Salida'
                        ELSE v_tipo
                    END,
                    v_tipo,
                    v_asistencia.id_asistencia,
                    v_asistencia.fecha AS fecha_asistencia,
                    v_asistencia.horario_entrada,
                    v_asistencia.horario_inicio_receso,
                    v_asistencia.horario_fin_receso,
                    v_asistencia.horario_salida;
                RETURN;
            END IF;
        END IF;
    END IF;

    SELECT
        q.id_tienda::TEXT,
        COALESCE(q.ubicacion, '{}'::JSONB),
        COALESCE(ti.nombre, 'Tienda')::TEXT,
        COALESCE(ti.direccion, '')::TEXT
    INTO
        v_id_tienda_qr,
        v_ubicacion_qr,
        v_nombre_tienda_qr,
        v_direccion_tienda_qr
    FROM public.qr q
    INNER JOIN public.tienda ti ON ti.id_tienda = q.id_tienda
    WHERE ti.estado = TRUE
      AND (
          trim(q.token::TEXT) = v_token
          OR public.payload_qr_valido_tienda(v_token, q.id_tienda)
      )
    LIMIT 1;

    IF v_id_tienda_qr IS NULL OR v_id_tienda_qr = '' THEN
        RETURN QUERY SELECT FALSE, 'QR invalido, vencido o no pertenece a una tienda activa.', NULL::TEXT,
            NULL::UUID, v_fecha AS fecha_asistencia, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ, NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    SELECT
        a.id_tienda::TEXT,
        upper(COALESCE(a.tipo, 'MULTIPLE'))::TEXT
    INTO
        v_ultima_tienda_tracking,
        v_ultimo_tipo_tracking
    FROM public.asistencia_multiple a
    WHERE a.id_trabajador::TEXT = trim(p_dni)
      AND (a.hora_marca AT TIME ZONE 'America/Lima')::DATE = v_fecha
    ORDER BY a.hora_marca DESC, a.id DESC
    LIMIT 1;

    IF v_ultimo_tipo_tracking = 'MULTIPLE'
       AND COALESCE(v_ultima_tienda_tracking, '') <> COALESCE(v_id_tienda_qr, '') THEN
        RETURN QUERY SELECT FALSE, 'Tu ultima marca de tracking fue en otra sede. Registra tracking en esta sede antes de marcar asistencia.',
            NULL::TEXT,
            NULL::UUID,
            v_fecha AS fecha_asistencia,
            NULL::TIMESTAMPTZ,
            NULL::TIMESTAMPTZ,
            NULL::TIMESTAMPTZ,
            NULL::TIMESTAMPTZ;
        RETURN;
    END IF;

    v_dia_semana := CASE extract(isodow FROM v_fecha)::INT
        WHEN 1 THEN 'lunes'
        WHEN 2 THEN 'martes'
        WHEN 3 THEN 'miercoles'
        WHEN 4 THEN 'jueves'
        WHEN 5 THEN 'viernes'
        WHEN 6 THEN 'sabado'
        WHEN 7 THEN 'domingo'
    END;

    SELECT
        TRUE,
        NOT (
            h.horario_inicio_receso IS NULL
            AND h.horario_fin_receso IS NULL
        )
    INTO
        v_tiene_horario,
        v_tiene_receso
    FROM public.horario_trabajador h
    WHERE h.dni_trabajador = trim(p_dni)
      AND h.dia_semana::TEXT = v_dia_semana
    LIMIT 1;

    v_tiene_horario := COALESCE(v_tiene_horario, FALSE);
    v_tiene_receso := COALESCE(v_tiene_receso, TRUE);
    v_justificado := v_tiene_horario;
    v_tipo_jornada_manual := lower(trim(COALESCE(p_tipo_jornada_manual, '')));

    IF NOT v_tiene_horario THEN
        IF v_tipo_jornada_manual IN ('parttime', 'part_time', '2_marcas') THEN
            v_tiene_receso := FALSE;
            v_justificado := FALSE;
        ELSIF v_tipo_jornada_manual IN ('fulltime', 'full_time', '4_marcas') THEN
            v_tiene_receso := TRUE;
            v_justificado := FALSE;
        END IF;
    END IF;

    SELECT *
    INTO v_asistencia
    FROM public.asistencia a
    WHERE a.dni_trabajador = trim(p_dni)
      AND a.fecha = v_fecha
    LIMIT 1;

    IF v_asistencia.id_asistencia IS NULL THEN
        INSERT INTO public.asistencia (
            dni_trabajador,
            fecha,
            horario_entrada,
            horario_inicio_receso,
            horario_fin_receso,
            horario_salida,
            ubicaciones,
            justificado
        )
        VALUES (
            trim(p_dni),
            v_fecha,
            NULL,
            NULL,
            NULL,
            NULL,
            CASE
                WHEN v_tipo_jornada_manual <> '' THEN jsonb_build_object(
                    '_jornada_manual',
                    jsonb_build_object(
                        'tipo_jornada', v_tipo_jornada_manual,
                        'tiene_receso', v_tiene_receso,
                        'registrado_en', v_ahora
                    )
                )
                ELSE '{}'::JSONB
            END,
            v_justificado
        )
        RETURNING *
        INTO v_asistencia;
    END IF;

    IF NOT v_tiene_horario THEN
        v_tipo_jornada_manual := lower(trim(COALESCE(
            NULLIF(v_tipo_jornada_manual, ''),
            v_asistencia.ubicaciones #>> '{_jornada_manual,tipo_jornada}',
            v_asistencia.ubicaciones ->> 'tipo_jornada_manual',
            ''
        )));

        IF v_tipo_jornada_manual IN ('parttime', 'part_time', '2_marcas') THEN
            v_tiene_receso := FALSE;
            v_justificado := FALSE;
        ELSIF v_tipo_jornada_manual IN ('fulltime', 'full_time', '4_marcas') THEN
            v_tiene_receso := TRUE;
            v_justificado := FALSE;
        END IF;

        IF v_tipo_jornada_manual <> '' THEN
            UPDATE public.asistencia
            SET
                justificado = v_justificado,
                ubicaciones = jsonb_set(
                    COALESCE(ubicaciones, '{}'::JSONB),
                    '{_jornada_manual}',
                    jsonb_build_object(
                        'tipo_jornada', v_tipo_jornada_manual,
                        'tiene_receso', v_tiene_receso,
                        'registrado_en', v_ahora
                    ),
                    TRUE
                )
            WHERE asistencia.id_asistencia = v_asistencia.id_asistencia
            RETURNING *
            INTO v_asistencia;
        END IF;
    END IF;

    SELECT MAX(marca)
    INTO v_ultima
    FROM (
        VALUES
            (v_asistencia.horario_entrada),
            (v_asistencia.horario_inicio_receso),
            (v_asistencia.horario_fin_receso),
            (v_asistencia.horario_salida)
    ) AS marcas(marca);

    IF v_ultima IS NOT NULL THEN
        v_restante := INTERVAL '10 minutes' - (v_ahora - v_ultima);
        IF v_restante > INTERVAL '0 seconds' THEN
            v_minutos := CEIL(EXTRACT(EPOCH FROM v_restante) / 60.0)::INTEGER;
            RETURN QUERY SELECT FALSE, 'Debes esperar ' || v_minutos || ' minutos antes de volver a marcar',
                NULL::TEXT,
                v_asistencia.id_asistencia,
                v_asistencia.fecha AS fecha_asistencia,
                v_asistencia.horario_entrada,
                v_asistencia.horario_inicio_receso,
                v_asistencia.horario_fin_receso,
                v_asistencia.horario_salida;
            RETURN;
        END IF;
    END IF;

    IF v_asistencia.horario_entrada IS NULL THEN
        v_tipo := 'horario_entrada';
    ELSIF v_tiene_receso AND v_asistencia.horario_inicio_receso IS NULL THEN
        v_tipo := 'horario_inicio_receso';
    ELSIF v_tiene_receso AND v_asistencia.horario_fin_receso IS NULL THEN
        v_tipo := 'horario_fin_receso';
    ELSIF v_asistencia.horario_salida IS NULL THEN
        v_tipo := 'horario_salida';
    ELSE
        RETURN QUERY SELECT FALSE, 'Ya completaste todas las marcaciones de hoy',
            NULL::TEXT,
            v_asistencia.id_asistencia,
            v_asistencia.fecha AS fecha_asistencia,
            v_asistencia.horario_entrada,
            v_asistencia.horario_inicio_receso,
            v_asistencia.horario_fin_receso,
            v_asistencia.horario_salida;
        RETURN;
    END IF;

    IF p_evento_id IS NOT NULL
       AND NULLIF(trim(COALESCE(p_tipo_marcacion_esperado, '')), '') IS NOT NULL
       AND v_tipo <> trim(p_tipo_marcacion_esperado) THEN
        RETURN QUERY SELECT FALSE,
            'El orden de la marca offline no coincide con la asistencia del servidor.',
            v_tipo,
            v_asistencia.id_asistencia,
            v_asistencia.fecha AS fecha_asistencia,
            v_asistencia.horario_entrada,
            v_asistencia.horario_inicio_receso,
            v_asistencia.horario_fin_receso,
            v_asistencia.horario_salida;
        RETURN;
    END IF;

    v_referencia_qr := public.extraer_ubicacion_qr(v_ubicacion_qr, v_tipo);
    IF v_referencia_qr IS NULL THEN
        RETURN QUERY SELECT FALSE, 'El QR no tiene ubicacion de referencia para validar el rango.',
            NULL::TEXT,
            v_asistencia.id_asistencia,
            v_asistencia.fecha AS fecha_asistencia,
            v_asistencia.horario_entrada,
            v_asistencia.horario_inicio_receso,
            v_asistencia.horario_fin_receso,
            v_asistencia.horario_salida;
        RETURN;
    END IF;

    IF NULLIF(v_referencia_qr ->> 'latitud', '') IS NULL
       OR NULLIF(v_referencia_qr ->> 'longitud', '') IS NULL THEN
        RETURN QUERY SELECT FALSE, 'El QR no tiene ubicacion de referencia para validar el rango.',
            NULL::TEXT,
            v_asistencia.id_asistencia,
            v_asistencia.fecha AS fecha_asistencia,
            v_asistencia.horario_entrada,
            v_asistencia.horario_inicio_receso,
            v_asistencia.horario_fin_receso,
            v_asistencia.horario_salida;
        RETURN;
    END IF;

    IF p_latitud IS NULL
       OR p_longitud IS NULL
       OR (
           abs(COALESCE(p_latitud, 0)) <= 0.000001
           AND abs(COALESCE(p_longitud, 0)) <= 0.000001
       ) THEN
        RETURN QUERY SELECT FALSE, 'No se pudo obtener tu ubicacion actual para validar el QR.',
            NULL::TEXT,
            v_asistencia.id_asistencia,
            v_asistencia.fecha AS fecha_asistencia,
            v_asistencia.horario_entrada,
            v_asistencia.horario_inicio_receso,
            v_asistencia.horario_fin_receso,
            v_asistencia.horario_salida;
        RETURN;
    END IF;

    v_distancia_qr := public.distancia_metros(
        NULLIF(v_referencia_qr ->> 'latitud', '')::DOUBLE PRECISION,
        NULLIF(v_referencia_qr ->> 'longitud', '')::DOUBLE PRECISION,
        p_latitud,
        p_longitud
    );

    IF v_distancia_qr > 150 THEN
        RETURN QUERY SELECT FALSE, 'Fuera del rango permitido del QR. Acercate a la sede para marcar.',
            NULL::TEXT,
            v_asistencia.id_asistencia,
            v_asistencia.fecha AS fecha_asistencia,
            v_asistencia.horario_entrada,
            v_asistencia.horario_inicio_receso,
            v_asistencia.horario_fin_receso,
            v_asistencia.horario_salida;
        RETURN;
    END IF;

    v_detalle_ubicacion := jsonb_strip_nulls(jsonb_build_object(
        'latitud', p_latitud,
        'longitud', p_longitud,
        'id_tienda_qr', v_id_tienda_qr,
        'nombre_tienda', v_nombre_tienda_qr,
        'direccion_tienda', v_direccion_tienda_qr
    ));

    IF v_tipo = 'horario_entrada' THEN
        UPDATE public.asistencia
        SET
            horario_entrada = v_ahora,
            justificado = v_justificado,
            ubicaciones = jsonb_set(
                COALESCE(ubicaciones, '{}'::JSONB),
                '{horario_entrada}',
                v_detalle_ubicacion,
                TRUE
            )
        WHERE asistencia.id_asistencia = v_asistencia.id_asistencia;
    ELSIF v_tipo = 'horario_inicio_receso' THEN
        UPDATE public.asistencia
        SET
            horario_inicio_receso = v_ahora,
            justificado = v_justificado,
            ubicaciones = jsonb_set(
                COALESCE(ubicaciones, '{}'::JSONB),
                '{horario_inicio_receso}',
                v_detalle_ubicacion,
                TRUE
            )
        WHERE asistencia.id_asistencia = v_asistencia.id_asistencia;
    ELSIF v_tipo = 'horario_fin_receso' THEN
        UPDATE public.asistencia
        SET
            horario_fin_receso = v_ahora,
            justificado = v_justificado,
            ubicaciones = jsonb_set(
                COALESCE(ubicaciones, '{}'::JSONB),
                '{horario_fin_receso}',
                v_detalle_ubicacion,
                TRUE
            )
        WHERE asistencia.id_asistencia = v_asistencia.id_asistencia;
    ELSIF v_tipo = 'horario_salida' THEN
        UPDATE public.asistencia
        SET
            horario_salida = v_ahora,
            justificado = v_justificado,
            ubicaciones = jsonb_set(
                COALESCE(ubicaciones, '{}'::JSONB),
                '{horario_salida}',
                v_detalle_ubicacion,
                TRUE
            )
        WHERE asistencia.id_asistencia = v_asistencia.id_asistencia;
    END IF;

    SELECT *
    INTO v_asistencia
    FROM public.asistencia a
    WHERE a.id_asistencia = v_asistencia.id_asistencia;

    IF p_evento_id IS NOT NULL THEN
        INSERT INTO public.marcacion_offline_evento (
            evento_id,
            dni_trabajador,
            fecha,
            tipo_marcacion,
            marcado_en,
            id_asistencia
        ) VALUES (
            p_evento_id,
            trim(p_dni),
            v_fecha,
            v_tipo,
            v_ahora,
            v_asistencia.id_asistencia
        )
        ON CONFLICT (evento_id) DO NOTHING;
    END IF;

    RETURN QUERY SELECT TRUE,
        CASE v_tipo
            WHEN 'horario_entrada' THEN 'Entrada'
            WHEN 'horario_inicio_receso' THEN 'Inicio de receso'
            WHEN 'horario_fin_receso' THEN 'Fin de receso'
            WHEN 'horario_salida' THEN 'Salida'
            ELSE v_tipo
        END,
        v_tipo,
        v_asistencia.id_asistencia,
        v_asistencia.fecha AS fecha_asistencia,
        v_asistencia.horario_entrada,
        v_asistencia.horario_inicio_receso,
        v_asistencia.horario_fin_receso,
        v_asistencia.horario_salida;
END;
$$;

