CREATE OR REPLACE FUNCTION public.extraer_ubicacion_qr(
    p_ubicacion JSONB,
    p_tipo TEXT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public
AS $$
DECLARE
    v_ubicacion JSONB := COALESCE(p_ubicacion, '{}'::JSONB);
    v_tipo TEXT := lower(trim(COALESCE(p_tipo, '')));
    v_key TEXT;
    v_value JSONB;
BEGIN
    IF jsonb_typeof(v_ubicacion) IS DISTINCT FROM 'object' THEN
        RETURN NULL;
    END IF;

    IF (
        v_ubicacion ?| ARRAY['latitud', 'latitude', 'lat']
        AND v_ubicacion ?| ARRAY['longitud', 'longitude', 'lng', 'lon']
    ) THEN
        RETURN jsonb_build_object(
            'latitud', COALESCE(v_ubicacion -> 'latitud', v_ubicacion -> 'latitude', v_ubicacion -> 'lat'),
            'longitud', COALESCE(v_ubicacion -> 'longitud', v_ubicacion -> 'longitude', v_ubicacion -> 'lng', v_ubicacion -> 'lon')
        );
    END IF;

    v_tipo := regexp_replace(v_tipo, '[[:space:]]+', '_', 'g');
    FOR v_key IN
        SELECT unnest(ARRAY[
            NULLIF(v_tipo, ''),
            CASE
                WHEN v_tipo IN ('entrada', 'horario_entrada') THEN 'horario_entrada'
                WHEN v_tipo IN ('inicio_de_receso', 'inicio_receso', 'horario_inicio_receso') THEN 'horario_inicio_receso'
                WHEN v_tipo IN ('fin_de_receso', 'fin_receso', 'horario_fin_receso') THEN 'horario_fin_receso'
                WHEN v_tipo IN ('salida', 'horario_salida') THEN 'horario_salida'
                ELSE NULL
            END
        ])
    LOOP
        IF v_key IS NULL OR NOT (v_ubicacion ? v_key) THEN
            CONTINUE;
        END IF;

        v_value := v_ubicacion -> v_key;
        IF jsonb_typeof(v_value) = 'object'
           AND v_value ?| ARRAY['latitud', 'latitude', 'lat']
           AND v_value ?| ARRAY['longitud', 'longitude', 'lng', 'lon'] THEN
            RETURN jsonb_build_object(
                'latitud', COALESCE(v_value -> 'latitud', v_value -> 'latitude', v_value -> 'lat'),
                'longitud', COALESCE(v_value -> 'longitud', v_value -> 'longitude', v_value -> 'lng', v_value -> 'lon')
            );
        END IF;
    END LOOP;

    FOR v_key, v_value IN
        SELECT key, value FROM jsonb_each(v_ubicacion)
    LOOP
        IF jsonb_typeof(v_value) = 'object'
           AND v_value ?| ARRAY['latitud', 'latitude', 'lat']
           AND v_value ?| ARRAY['longitud', 'longitude', 'lng', 'lon'] THEN
            RETURN jsonb_build_object(
                'latitud', COALESCE(v_value -> 'latitud', v_value -> 'latitude', v_value -> 'lat'),
                'longitud', COALESCE(v_value -> 'longitud', v_value -> 'longitude', v_value -> 'lng', v_value -> 'lon')
            );
        END IF;
    END LOOP;

    RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.extraer_ubicacion_qr(JSONB, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.extraer_ubicacion_qr(JSONB, TEXT) TO anon;
GRANT EXECUTE ON FUNCTION public.extraer_ubicacion_qr(JSONB, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.distancia_metros(
    p_latitud_a DOUBLE PRECISION,
    p_longitud_a DOUBLE PRECISION,
    p_latitud_b DOUBLE PRECISION,
    p_longitud_b DOUBLE PRECISION
) RETURNS DOUBLE PRECISION
LANGUAGE sql
IMMUTABLE
STRICT
SET search_path = public
AS $$
    SELECT 6371000.0 * 2.0 * asin(LEAST(1.0, sqrt(
        power(sin(radians((p_latitud_b - p_latitud_a) / 2.0)), 2) +
        cos(radians(p_latitud_a)) *
        cos(radians(p_latitud_b)) *
        power(sin(radians((p_longitud_b - p_longitud_a) / 2.0)), 2)
    )));
$$;

